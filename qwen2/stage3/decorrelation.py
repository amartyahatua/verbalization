"""
Stage 3 core design: the 2x2 decorrelation test.

DIRECTION STATE (X vs Y): built as a single bipolar axis, not two
separate unipolar directions -- d_XY = normalize(jspace_vec_X -
jspace_vec_Y), reusing the Stage 1 bank's per-token J-space vectors.
Clamping to +alpha represents "direction says X"; -alpha represents
"direction says Y". This is the standard way this kind of conflict
design is built (see e.g. ROME/CounterFact-style subject-object
contrasts) and it's the only construction that makes "direction state"
a genuine two-level factor crossable with input content, rather than
two unrelated single-concept directions.

INPUT CONTENT (X vs Y): a neutral, passive context sentence mentioning
the concept -- NOT a completion prompt requiring the model to
generate anything about it. This is what makes the "injection-then-
report" confound-(a) fix work (see stage3_run.py): since the model is
never asked to produce a behavioral response to the input before the
elicitation report, there is no prior own-generated text for the
report to leak from -- the report is the model's first and only
generation in the whole prompt.

Only the two CONFLICT cells (direction=X,input=Y) and
(direction=Y,input=X) are used for H3's actual test; the two
congruent cells are also computed (by stage3_run.py) as a sanity
check that the pipeline behaves sensibly when direction and input
agree, but they aren't part of the direction-following index itself.
"""

import torch
from typing import List, Optional

# --- make stage2/ importable from here (same pattern stage2 uses to reach stage1) ---
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "stage2"))

import random

from scoring import exact_match_score, score_reports


def build_bipolar_direction(vec_x: torch.Tensor, vec_y: torch.Tensor) -> torch.Tensor:
    d = vec_x / vec_x.norm() - vec_y / vec_y.norm()
    return d / d.norm()


def build_input_content(concept: str, template: str = "A note nearby reads: \"{concept}\".") -> str:
    return template.format(concept=concept)


def build_cell_prompt(input_concept: str, elicitation_prompt: str, template: Optional[str] = None) -> str:
    """
    The full generation prompt for one cell: passive input content,
    then the fixed elicitation question. The model's first generated
    tokens ARE the report -- nothing generated by the model appears
    earlier in this prompt for it to "re-read".
    """
    content = build_input_content(input_concept, template) if template else build_input_content(input_concept)
    return f"{content}\n{elicitation_prompt}"


def direction_following_index(
    reports_dir_x_input_y: List[str],
    reports_dir_y_input_x: List[str],
    x: str,
    y: str,
    all_labels: Optional[List[str]] = None,
) -> dict:
    """
    On each conflict cell, compute P(report matches direction) -
    P(report matches input), then average across both conflict cells
    (each already signed so positive = direction wins in both).

    Returns per-cell rates too, since a cell-level asymmetry (e.g.
    direction always wins when it says X but never when it says Y)
    is itself an interesting/important thing to be able to see rather
    than only the averaged index.

    all_labels: the full set of labels the underlying model could
    plausibly recite (e.g. every pair trained on, not just this one)
    -- passed through to exact_match_score's shotgun-listing check.
    Defaults to just [x, y] when not given, since a report mentioning
    BOTH x and y is uninformative for DFI regardless of what else the
    model might know; pass the broader set when evaluating a trained
    adapter that could hedge across pairs it was never asked about
    here specifically.
    """
    candidate_labels = all_labels if all_labels is not None else [x, y]

    def rate(reports, target):
        scores = [exact_match_score(r, target, candidate_labels=candidate_labels) for r in reports]
        scores = [s for s in scores if s is not None]
        return sum(scores) / len(scores) if scores else None

    # cell 1: direction says X, input says Y -- direction "wins" if report matches X
    p_dir_x = rate(reports_dir_x_input_y, x)
    p_input_y = rate(reports_dir_x_input_y, y)
    dfi_cell1 = (p_dir_x - p_input_y) if (p_dir_x is not None and p_input_y is not None) else None

    # cell 2: direction says Y, input says X -- direction "wins" if report matches Y
    p_dir_y = rate(reports_dir_y_input_x, y)
    p_input_x = rate(reports_dir_y_input_x, x)
    dfi_cell2 = (p_dir_y - p_input_x) if (p_dir_y is not None and p_input_x is not None) else None

    vals = [v for v in (dfi_cell1, dfi_cell2) if v is not None]
    overall = sum(vals) / len(vals) if vals else None

    # Exact counts behind every probability above (k out of n scorable generations), so a table can
    # report "5/12" rather than a bare percentage, and a reader can see how thin a cell is.
    counts = {
        "dirX_matches_X": score_reports(reports_dir_x_input_y, x, candidate_labels),
        "dirX_matches_Y_input": score_reports(reports_dir_x_input_y, y, candidate_labels),
        "dirY_matches_Y": score_reports(reports_dir_y_input_x, y, candidate_labels),
        "dirY_matches_X_input": score_reports(reports_dir_y_input_x, x, candidate_labels),
    }

    return {
        "dfi_cell1_dirX_inputY": dfi_cell1,
        "dfi_cell2_dirY_inputX": dfi_cell2,
        "dfi_overall": overall,
        "p_dirX_matches_X": p_dir_x,
        "p_dirX_matches_Y_input": p_input_y,
        "p_dirY_matches_Y": p_dir_y,
        "p_dirY_matches_X_input": p_input_x,
        "counts": counts,
        "n_generations": len(reports_dir_x_input_y) + len(reports_dir_y_input_x),
    }


def dfi_bootstrap(
    reports_dir_x_input_y: List[str],
    reports_dir_y_input_x: List[str],
    x: str,
    y: str,
    all_labels: Optional[List[str]] = None,
    n_boot: int = 2000,
    seed: int = 0,
) -> dict:
    """
    Percentile-bootstrap interval for DFI of ONE (pair, layer) entry, resampling the GENERATIONS
    within each conflict cell. This captures sampling noise in the decoded reports only -- it says
    nothing about training-seed variance (use multiple adapter seeds + stage6/aggregate_seeds.py for
    that) or about coverage of the pair/layer set (stage6 bootstraps across entries for that).
    With the default 3 generations per cell the interval is necessarily wide; that is the point.

    DFI here is the same quantity direction_following_index returns:
        0.5 * [ (P(report=X|d=X,i=Y) - P(report=Y|d=X,i=Y)) + (P(report=Y|d=Y,i=X) - P(report=X|d=Y,i=X)) ]
    """
    candidate_labels = all_labels if all_labels is not None else [x, y]

    def indicators(reports, target):
        return [exact_match_score(r, target, candidate_labels=candidate_labels) for r in reports]

    c1_dir, c1_inp = indicators(reports_dir_x_input_y, x), indicators(reports_dir_x_input_y, y)
    c2_dir, c2_inp = indicators(reports_dir_y_input_x, y), indicators(reports_dir_y_input_x, x)
    n1, n2 = len(reports_dir_x_input_y), len(reports_dir_y_input_x)
    if n1 == 0 or n2 == 0:
        return {"mean": None, "ci_low": None, "ci_high": None, "n_boot": n_boot}

    def dfi_from(idx1, idx2):
        cell1 = sum(c1_dir[i] for i in idx1) / len(idx1) - sum(c1_inp[i] for i in idx1) / len(idx1)
        cell2 = sum(c2_dir[i] for i in idx2) / len(idx2) - sum(c2_inp[i] for i in idx2) / len(idx2)
        return 0.5 * (cell1 + cell2)

    point = dfi_from(list(range(n1)), list(range(n2)))
    rng = random.Random(seed)
    boots = sorted(dfi_from([rng.randrange(n1) for _ in range(n1)], [rng.randrange(n2) for _ in range(n2)])
                   for _ in range(n_boot))
    return {"mean": point, "ci_low": boots[int(0.025 * n_boot)], "ci_high": boots[min(n_boot - 1, int(0.975 * n_boot))],
            "n_boot": n_boot, "resampled": "generations within each conflict cell"}
